// Netlify runs this before publishing (see netlify.toml). It checks public/config.js and writes the files that depend on it:
//   public/_redirects  the proxies to your game server's public API (and the report lookup, if REPORT_LOOKUP is on)
//   public/_headers    the security headers, with your Supabase address allowed
//   showcase/site/site-config.js  the server and alliance for the public alliance page
// Run it yourself with `node scripts/build.mjs` to check your settings. A problem stops the build, on purpose.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { readConfig } = require('./read-config.cjs')
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

const { config: c, problems } = readConfig()
if (problems.length) {
  console.error('\n✋ public/config.js needs fixing:\n' + problems.map((p) => '  - ' + p).join('\n') + '\n')
  process.exit(1)
}

const game = `https://${c.OGAME_SERVER}.ogame.gameforge.com`
const redirects = [
  '# Generated by scripts/build.mjs from public/config.js. Do not edit; edit config.js.',
  `/api/*  ${game}/api/:splat  200`,
  // ":id" matches exactly one path segment, so only /ogapi/v1/report/<id>/true is passed on
  c.REPORT_LOOKUP ? '/ogapi/v1/report/:id/true  https://ogapi.faw-kes.de/v1/report/:id/true  200' : '',
].filter(Boolean).join('\n') + '\n'

const csp = `default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self' ${c.SUPABASE_URL}; base-uri 'none'; form-action 'self'; frame-ancestors 'none'`
const headers = `# Generated by scripts/build.mjs from public/config.js. Do not edit; edit config.js.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  X-Frame-Options: DENY
/sw.js
  Cache-Control: no-cache
/api/*
  Cache-Control: public, max-age=600, s-maxage=600
`
fs.writeFileSync(path.join(ROOT, 'public', '_redirects'), redirects)
fs.writeFileSync(path.join(ROOT, 'public', '_headers'), headers)

// the public alliance page gets only the server and our tag, never the database settings
const site = `// Generated by scripts/build.mjs from public/config.js. Do not edit.\nconst SITE = ${JSON.stringify({ server: c.OGAME_SERVER, home: c.OUR_ALLIANCE })}\n`
fs.writeFileSync(path.join(ROOT, 'showcase', 'site', 'site-config.js'), site)
fs.writeFileSync(path.join(ROOT, 'showcase', 'site', '_redirects'), `# Generated by scripts/build.mjs. Only the public game files the map needs.\n${['universe', 'players', 'alliances', 'serverData', 'highscore'].map((f) => `/api/${f}.xml  ${game}/api/${f}.xml  200`).join('\n')}\n`)

console.log(`✅ config ok: ${c.OGAME_SERVER}, ${c.OUR_ALLIANCE} vs ${c.ENEMY_ALLIANCE}, report lookup ${c.REPORT_LOOKUP ? 'on' : 'off'}, alerts ${c.VAPID_PUBLIC_KEY ? 'on' : 'off'}`)
